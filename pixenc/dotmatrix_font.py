"""5x7 dot-matrix LED-style font.

Every pixel in the 7-row x 5-col cell is directly addressable (no segment
topology). Glyph shapes follow canonical IBM/HD44780 5x7 LED dot-matrix
conventions, with hand-tuning on the worst-case Hamming-confusable pairs
(D vs O, M vs N, S vs 5, 8 vs 6/9, P vs F/R) to push d_min up.

Lowercase and basic punctuation are included so the font covers a real
text alphabet, not just A-Z + digits.
"""

