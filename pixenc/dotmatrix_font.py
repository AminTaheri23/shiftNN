# Validate that every glyph row is exactly DM_COLS chars (catches typos).
for _ch, _rows in _glyphs.items():
    assert len(_rows) == DM_ROWS, f"glyph {_ch!r} has {len(_rows)} rows, expected {DM_ROWS}"
    for _i, _row in enumerate(_rows):
        assert len(_row) == DM_COLS, (
            f"glyph {_ch!r} row {_i} has {len(_row)} cols ({_row!r}), expected {DM_COLS}"
        )


alphabet_dm = {ch: _parse(rows) for ch, rows in _glyphs.items()}

# Convenience subsets for apples-to-apples comparisons against the segment fonts.
UPPER_DIGITS = [c for c in alphabet_dm
                if (c.isalpha() and c.isupper()) or c.isdigit()]
LOWER = [c for c in alphabet_dm if c.isalpha() and c.islower()]
PUNCT = [c for c in alphabet_dm if not c.isalnum() and c != " "]


def render_char_dm(ch):
    key = ch
    if key not in alphabet_dm:
        # case-fold uppercase only when the input is missing.
        upper = ch.upper()
        if upper in alphabet_dm:
            key = upper
        else:
            raise KeyError(f"Character {ch!r} not in dot-matrix alphabet")
    return alphabet_dm[key].copy()


def render_word_dm(word, k=DEFAULT_K):
    out = np.zeros((DM_ROWS, DM_COLS * k), dtype=bool)
    for idx, ch in enumerate(word[:k]):
        out[:, idx * DM_COLS:(idx + 1) * DM_COLS] = render_char_dm(ch)
    return out
