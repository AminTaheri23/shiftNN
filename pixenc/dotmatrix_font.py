DM_ROWS = 7
DM_COLS = 5
DM_BITS = DM_ROWS * DM_COLS  # 35

# K = number of letter-cells per word-bitmap. Locked at 12 after the K-sweep:
# K=12 covers 95% of the vocab without truncation, drops collision rate to
# 2.1%, and bits/word stays modest (35 * 12 = 420 bits). See experiments/scan_K.py.
DEFAULT_K = 12


def _parse(rows):
    arr = np.zeros((DM_ROWS, DM_COLS), dtype=bool)
    for r, line in enumerate(rows):
        for c, ch in enumerate(line):
            arr[r, c] = (ch == "#")
    return arr


